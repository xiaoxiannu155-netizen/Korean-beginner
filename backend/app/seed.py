async def seed_all(db: AsyncSession, scope: str = "all"):
    """导入全部种子数据

    Args:
        db: 数据库 session
        scope: 'all' | 'letters' | 'words' | 'grammar' | 'batchim' | 'sentences'
    """
    if scope in ("all", "letters"):
        await seed_letters(db)
        await seed_syllable_rules(db)
        await seed_sound_changes(db)
    if scope in ("all", "words"):
        await seed_words(db)
    if scope in ("all", "sentences"):
        await seed_extra_sentences(db)
    if scope in ("all", "grammar"):
        await seed_grammar(db)
    if scope in ("all", "batchim"):
        await seed_batchim_rules(db)

    if scope == "all":
        print(f"Full MVP seed complete!")


async def seed_letters(db: AsyncSession):
    """导入完整韩文字母课程 (60+ 单元)"""
    index = 0
    total = 0

    for char, rom, hint, tip in BASIC_VOWELS:
        index += 1; total += 1
        db.add(Letter(
            char=char, type="basic_vowel", romanization=rom,
            chinese_hint=hint, pronunciation_tip=tip,
            order_index=index,
        ))

    for char, rom, hint, tip in COMPOUND_VOWELS:
        index += 1; total += 1
        db.add(Letter(
            char=char, type="compound_vowel", romanization=rom,
            chinese_hint=hint, pronunciation_tip=tip,
            order_index=index,
        ))

    for char, rom, hint, tip in BASIC_CONSONANTS:
        index += 1; total += 1
        db.add(Letter(
            char=char, type="consonant", romanization=rom,
            chinese_hint=hint, pronunciation_tip=tip,
            order_index=index,
        ))

    for char, rom, hint, tip in DOUBLE_CONSONANTS:
        index += 1; total += 1
        db.add(Letter(
            char=char, type="double_consonant", romanization=rom,
            chinese_hint=hint, pronunciation_tip=tip,
            order_index=index,
        ))

    await db.commit()
    print(f"  Seeded {total} alphabet units (vowels: {10+11}, consonants: {14+5})")


async def seed_syllable_rules(db: AsyncSession):
    """导入拼读规则"""
    index = 0
    for title, rule_type, description, example in SYLLABLE_RULES:
        index += 1
        # 使用 Letter 表存储拼读规则
        db.add(Letter(
            char=f"rule_{rule_type}", type="syllable_rule",
            romanization=title, chinese_hint=description,
            pronunciation_tip=example, order_index=index + 100,
        ))
    await db.commit()
    print(f"  Seeded {index} syllable rules")


async def seed_sound_changes(db: AsyncSession):
    """导入音变规则 (使用 BatchimRule 表)"""
    for title, rule_type, desc_ko, desc_zh, examples in SOUND_CHANGE_RULES:
        rule = BatchimRule(
            rule_type=rule_type, title=title,
            description=f"{desc_zh}\n\n{desc_ko}",
            order_index={
                "liaison": 1, "nasalization": 2, "tensification": 3,
                "aspiration": 4, "lateralization": 5,
            }.get(rule_type, 0),
        )
        db.add(rule)
        await db.flush()

        for written, pronounced, process in examples:
            db.add(BatchimExample(
                rule_id=rule.id,
                written_form=written, pronounced_form=pronounced,
                process_description=process,
            ))
    await db.commit()
    print(f"  Seeded {len(SOUND_CHANGE_RULES)} sound change rules with examples")


async def seed_words(db: AsyncSession):
    """导入完整单词库 (500+ 词)"""
    all_words = WORD_DATA + MORE_WORDS
    count = 0
    example_count = 0

    for korean, chinese, romanization, category, sub_category, difficulty, examples in all_words:
        w = Word(
            korean=korean, chinese=chinese, romanization=romanization,
            category=category, sub_category=sub_category,
            difficulty_level=difficulty,
        )
        db.add(w)
        await db.flush()

        for ex_data in examples:
            if len(ex_data) == 3:
                ex_ko, ex_zh, ex_type = ex_data
                ex_source = None
            else:
                ex_ko, ex_zh, ex_type, ex_source = ex_data
            db.add(WordExample(
                word_id=w.id, korean_sentence=ex_ko,
                chinese_translation=ex_zh, source_type=ex_type,
                source_name=ex_source,
            ))
            example_count += 1

        count += 1

    await db.commit()
    print(f"  Seeded {count} words with {example_count} examples")


async def seed_extra_sentences(db: AsyncSession):
    """导入额外基础例句"""
    count = 0
    for category, ko, zh, source in EXTRA_SENTENCES:
        # 额外例句作为独立句子存储
        db.add(WordExample(
            word_id=None,
            korean_sentence=ko,
            chinese_translation=zh,
            source_type=category,
            source_name=source,
        ))
        count += 1
    await db.commit()
    print(f"  Seeded {count} extra sentences")


async def seed_grammar(db: AsyncSession):
    """导入语法课程"""
    count = 0
    for level, title, desc_zh, usage, formula, examples in GRAMMAR_DATA:
        gp = GrammarPoint(
            title=title, level=level,
            structure_formula=formula, explanation=desc_zh,
            usage_scenario=usage,
            order_index=count + 1,
        )
        db.add(gp)
        await db.flush()

        for ex_ko, ex_zh, is_wrong in examples:
            db.add(GrammarExample(
                grammar_id=gp.id, korean_sentence=ex_ko,
                chinese_translation=ex_zh, is_wrong_example=is_wrong,
            ))
        count += 1

    await db.commit()
    print(f"  Seeded {count} grammar points with examples")


